//! The shared air-gap fixtures in `vectors/ur/`: real signer views and a
//! real `.zsig` as the parts this crate encodes. The firmware's simulator
//! (`firmware/sim/test_ur_fixtures.c`) checks the same files: its encoder
//! must print the same lines and its decoder must read them. So Rust → C and
//! C → Rust are both covered without a board.
//!
//! Regenerate (only when a fixture is added): `LEEK_UR_REGEN=1 cargo test
//! -p leek-ur --test fixtures`.

use std::path::{Path, PathBuf};

use leek_ur::{decode_bytes, wrap_bytes, Decoder, Encoder, Received, UrError, UR_PCZT, UR_ZSIG};

struct Fixture {
    file: &'static str,
    source: &'static str,
    ur_type: &'static str,
    max_fragment: usize,
    /// Parts written: seq_len plus this many fountain parts.
    extra: u32,
}

/// The files `test_ur_fixtures.c` lists too.
const FIXTURES: &[Fixture] = &[
    Fixture { file: "iw_send_nu7_compact.50.leek-pczt", source: "pczt/iw_send_nu7_compact.pczt", ur_type: UR_PCZT, max_fragment: 50, extra: 20 },
    Fixture { file: "main_iw_send_nu7_compact.120.leek-pczt", source: "pczt/main_iw_send_nu7_compact.pczt", ur_type: UR_PCZT, max_fragment: 120, extra: 10 },
    Fixture { file: "iw_send_shielded.512.leek-zsig", source: "zsig/iw_send_shielded.zsig", ur_type: UR_ZSIG, max_fragment: 512, extra: 0 },
    Fixture { file: "iw_send_shielded.30.leek-zsig", source: "zsig/iw_send_shielded.zsig", ur_type: UR_ZSIG, max_fragment: 30, extra: 8 },
];

fn vectors() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../vectors")
}

fn render(f: &Fixture, payload: &[u8]) -> String {
    let e = Encoder::new(f.ur_type, &wrap_bytes(payload), f.max_fragment).unwrap();
    let mut s = format!(
        "# ur:{} of vectors/{} (CBOR byte string), max fragment {}: {} x {} B, checksum {}\n# Generated by host/leek-ur/tests/fixtures.rs; read by firmware/sim/test_ur_fixtures.c. Do not edit.\n",
        f.ur_type,
        f.source,
        f.max_fragment,
        e.seq_len(),
        e.fragment_len(),
        e.checksum()
    );
    let n = if e.is_single_part() { 1 } else { e.seq_len() + f.extra };
    for seq in 1..=n {
        s.push_str(&e.part(seq).unwrap());
        s.push('\n');
    }
    s
}

fn parts(text: &str) -> Vec<&str> {
    text.lines().filter(|l| !l.is_empty() && !l.starts_with('#')).collect()
}

fn load(f: &Fixture) -> (Vec<u8>, String) {
    let payload = std::fs::read(vectors().join(f.source)).unwrap();
    let path = vectors().join("ur").join(format!("{}.txt", f.file));
    if std::env::var_os("LEEK_UR_REGEN").is_some() {
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        std::fs::write(&path, render(f, &payload)).unwrap();
    }
    let text = std::fs::read_to_string(&path).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
    (payload, text)
}

#[test]
fn encoder_prints_the_fixtures() {
    for f in FIXTURES {
        let (payload, text) = load(f);
        assert_eq!(render(f, &payload), text, "{} changed", f.file);
    }
}

#[test]
fn decoder_reads_the_fixtures_every_way() {
    for f in FIXTURES {
        let (payload, text) = load(f);
        let p = parts(&text);
        // In order, and uppercase as the QR alphanumeric mode carries them.
        assert_eq!(decode_bytes(f.ur_type, p.iter().copied()).unwrap(), payload, "{}", f.file);
        let upper: Vec<String> = p.iter().map(|x| x.to_uppercase()).collect();
        assert_eq!(decode_bytes(f.ur_type, upper.iter().map(String::as_str)).unwrap(), payload);
        if p.len() == 1 {
            continue;
        }
        // Reversed, rotated and with every part twice: the fountain
        // parts at the end stand in for the plain ones missed.
        let rev: Vec<&str> = p.iter().rev().copied().collect();
        assert_eq!(decode_bytes(f.ur_type, rev).unwrap(), payload, "{} reversed", f.file);
        let mut dup: Vec<&str> = Vec::new();
        for (i, x) in p.iter().enumerate() {
            if i % 8 != 1 {
                dup.push(x);
                dup.push(x);
            }
        }
        dup.rotate_left(p.len() / 3);
        let mut d = Decoder::new();
        let mut complete = false;
        for x in &dup {
            if d.receive(x).unwrap() == Received::Complete {
                complete = true;
                break;
            }
        }
        assert!(complete, "{}: an eighth of the parts dropped, the rest doubled", f.file);
    }
}

#[test]
fn the_wrong_type_is_refused() {
    let (_, text) = load(&FIXTURES[0]);
    assert!(matches!(decode_bytes(UR_ZSIG, parts(&text)), Err(UrError::WrongType { .. })));
    // Too few parts.
    let (_, text) = load(&FIXTURES[3]);
    assert!(matches!(decode_bytes(UR_ZSIG, parts(&text).into_iter().take(1)), Err(UrError::Incomplete { .. })));
}

#[test]
fn fixtures_exist_for_the_c_suite() {
    let c = std::fs::read_to_string(Path::new(env!("CARGO_MANIFEST_DIR")).join("../../firmware/sim/test_ur_fixtures.c")).unwrap();
    for f in FIXTURES {
        assert!(c.contains(f.file), "test_ur_fixtures.c does not list {}", f.file);
    }
}
