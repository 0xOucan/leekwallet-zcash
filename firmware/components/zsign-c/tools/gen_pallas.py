#!/usr/bin/env python3
"""Generate the Pallas field and curve constants for zc_pallas.c.

Everything here is derived from the two moduli and from the constants
pasta_curves 0.6 publishes (iso-Pallas A and B, the 3-isogeny coefficients,
the SSWU Z); nothing is copied from another C implementation. Each value is
asserted against its definition before it is emitted.

Output: zc_pallas_consts.h, 8 little-endian 32-bit limbs per value.
Montgomery-form values (R = 2^256) are marked _M; plain integers (exponents,
moduli) are not.

Usage: gen_pallas.py > zc_pallas_consts.h
"""

P = 0x40000000000000000000000000000000224698FC094CF91B992D30ED00000001
Q = 0x40000000000000000000000000000000224698FC0994A8DD8C46EB2100000001
R = 1 << 256


def limbs(v):
    assert 0 <= v < R
    return [(v >> (32 * i)) & 0xFFFFFFFF for i in range(8)]


def raw(l):
    """pasta_curves from_raw: four little-endian u64 limbs."""
    return sum(x << (64 * i) for i, x in enumerate(l))


def emit(name, v):
    body = ", ".join("0x%08x" % x for x in limbs(v))
    print("static const uint32_t %s[8] = { %s };" % (name, body))


def mont(v, m):
    return (v * R) % m


# ---- moduli -----------------------------------------------------------------
for m in (P, Q):
    assert m % (1 << 32) == 1          # so -m^-1 mod 2^32 = 0xffffffff
    assert pow(2, m - 1, m) == 1       # prime (Fermat; both are known primes)

# ---- square roots in Fp: p - 1 = 2^S * T, T odd -----------------------------
S = 0
T = P - 1
while T % 2 == 0:
    T //= 2
    S += 1
assert S == 32
GEN = 5                                 # pasta_curves Fp::MULTIPLICATIVE_GENERATOR
assert pow(GEN, (P - 1) // 2, P) == P - 1   # a non-residue
ROOT = pow(GEN, T, P)                   # primitive 2^32-th root of unity
assert pow(ROOT, 1 << 31, P) == P - 1

# ---- curves -------------------------------------------------------------------
B = 5
ISO_A = raw([0x92bb4b0b657a014b, 0xb74134581a27a59f, 0x49be2d7258370742, 0x18354a2eb0ea8c9c])
ISO_B = 1265
Z = P - 13
assert raw([0x992d30ecfffffff4, 0x224698fc094cf91b, 0, 0x4000000000000000]) == Z
ISO = [raw(x) for x in [
    [0x775f6034aaaaaaab, 0x4081775473d8375b, 0xe38e38e38e38e38e, 0x0e38e38e38e38e38],
    [0x8cf863b02814fb76, 0x0f93b82ee4b99495, 0x267c7ffa51cf412a, 0x3509afd51872d88e],
    [0x0eb64faef37ea4f7, 0x380af066cfeb6d69, 0x98c7d7ac3d98fd13, 0x17329b9ec5253753],
    [0xeebec06955555580, 0x8102eea8e7b06eb6, 0xc71c71c71c71c71c, 0x1c71c71c71c71c71],
    [0xc47f2ab668bcd71f, 0x9c434ac1c96b6980, 0x5a607fcce0494a79, 0x1d572e7ddc099cff],
    [0x2aa3af1eae5b6604, 0xb4abf9fb9a1fc81c, 0x1d13bf2a7f22b105, 0x325669becaecd5d1],
    [0x5ad985b5e38e38e4, 0x7642b01ad461bad2, 0x4bda12f684bda12f, 0x1a12f684bda12f68],
    [0xc67c31d8140a7dbb, 0x07c9dc17725cca4a, 0x133e3ffd28e7a095, 0x1a84d7ea8c396c47],
    [0x02e2be87d225b234, 0x1765e924f7459378, 0x303216cce1db9ff1, 0x3fb98ff0d2ddcadd],
    [0x93e53ab371c71c4f, 0x0ac03e8e134eb3e4, 0x7b425ed097b425ed, 0x025ed097b425ed09],
    [0x5a28279b1d1b42ae, 0x5941a3a4a97aa1b3, 0x0790bfb3506defb6, 0x0c02c5bcca0e6b7f],
    [0x4d90ab820b12320a, 0xd976bbfabbc5661d, 0x573b3d7f7d681310, 0x17033d3c60c68173],
    [0x992d30ecfffffde5, 0x224698fc094cf91b, 0x0000000000000000, 0x4000000000000000],
]]


def on_iso(x, y):
    return (y * y - (x ** 3 + ISO_A * x + ISO_B)) % P == 0


def on_pallas(x, y):
    return (y * y - (x ** 3 + B)) % P == 0


def sqrt_p(a):
    # Tonelli-Shanks, for the self-check only.
    a %= P
    if a == 0:
        return 0
    if pow(a, (P - 1) // 2, P) != 1:
        return None
    m, c, t, r = S, ROOT, pow(a, T, P), pow(a, (T + 1) // 2, P)
    while t != 1:
        i, tt = 0, t
        while tt != 1:
            tt = tt * tt % P
            i += 1
        b = pow(c, 1 << (m - i - 1), P)
        m, c, t, r = i, b * b % P, t * b * b % P, r * b % P
    return r


def iso_map(x, y):
    num_x = ((ISO[0] * x + ISO[1]) * x + ISO[2]) * x + ISO[3]
    div_x = (x + ISO[4]) * x + ISO[5]
    num_y = (((ISO[6] * x + ISO[7]) * x + ISO[8]) * x + ISO[9]) * y
    div_y = ((x + ISO[10]) * x + ISO[11]) * x + ISO[12]
    return num_x * pow(div_x, P - 2, P) % P, num_y * pow(div_y, P - 2, P) % P


# The isogeny maps iso-Pallas points onto Pallas: check a few.
n = 0
x = 1
while n < 8:
    y = sqrt_p(x ** 3 + ISO_A * x + ISO_B)
    if y is not None:
        assert on_iso(x, y)
        assert on_pallas(*iso_map(x, y))
        n += 1
    x += 1

print("/* Generated by tools/gen_pallas.py. Do not edit. */")
print("/* Pallas p and q, Montgomery constants (R = 2^256), square-root and")
print(" * hash-to-curve constants (pasta_curves 0.6: iso-Pallas, SSWU Z = -13). */")
print("#pragma once")
print("#include <stdint.h>")
for name, m in (("P", P), ("Q", Q)):
    emit("ZC_%s" % name, m)
    emit("ZC_%s_R2" % name, R * R % m)
    emit("ZC_%s_R3" % name, R * R * R % m)
    emit("ZC_%s_MINUS2" % name, m - 2)
emit("ZC_P_T_MINUS1_HALF", (T - 1) // 2)
emit("ZC_P_ROOT_M", mont(ROOT, P))
emit("ZC_P_ISO_A_M", mont(ISO_A, P))
emit("ZC_P_ISO_B_M", mont(ISO_B, P))
emit("ZC_P_SSWU_Z_M", mont(Z, P))
print("static const uint32_t ZC_P_ISO_M[13][8] = {")
for v in ISO:
    print("    { %s }," % ", ".join("0x%08x" % x for x in limbs(mont(v, P))))
print("};")
print("#define ZC_P_TWO_ADICITY %d" % S)
