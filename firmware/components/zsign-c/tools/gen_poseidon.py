#!/usr/bin/env python3
"""Generate the Poseidon P128Pow5T3 constants over the Pallas base field.

Implements the parameter generation of the Poseidon paper's reference script
(generate_parameters_grain.sage, with the arguments the Orchard nullifier PRF
uses: field=1 sbox=0 n=255 t=3 R_F=8 R_P=56, p = Pallas base modulus):

  * an 80-bit Grain LFSR seeded with the parameters, 160 warm-up bits
    discarded, output bits filtered pairwise (emit b2 when b1 == 1);
  * 64 * 3 round constants, each 255 bits MSB-first, rejection-sampled < p;
  * the MDS matrix as a Cauchy matrix 1 / (x_i + y_j) from 2t further
    255-bit samples reduced mod p (no rejection), resampled if not distinct.

Output: zc_poseidon_consts.h, in Montgomery form for zc_pallas.c. The result is
checked by test_zcash_pczt_c against the published Poseidon/Orchard test
vectors and, end to end, against every nullifier in the PCZT vectors.

Usage: gen_poseidon.py > zc_poseidon_consts.h
"""

P = 0x40000000000000000000000000000000224698FC094CF91B992D30ED00000001
N, T, RF, RP = 255, 3, 8, 56


class Grain:
    def __init__(self):
        bits = []

        def put(v, n):
            bits.extend((v >> (n - 1 - i)) & 1 for i in range(n))

        put(1, 2)      # field type: prime
        put(0, 4)      # sbox: x^alpha
        put(N, 12)
        put(T, 12)
        put(RF, 10)
        put(RP, 10)
        bits.extend([1] * 30)
        assert len(bits) == 80
        self.s = bits
        for _ in range(160):
            self._step()

    def _step(self):
        s = self.s
        b = s[62] ^ s[51] ^ s[38] ^ s[23] ^ s[13] ^ s[0]
        self.s = s[1:] + [b]
        return b

    def bit(self):
        while True:
            b1 = self._step()
            b2 = self._step()
            if b1:
                return b2

    def bits_int(self, n):
        v = 0
        for _ in range(n):
            v = (v << 1) | self.bit()
        return v

    def field_rejection(self):
        while True:
            v = self.bits_int(N)
            if v < P:
                return v

    def field_wide(self):
        return self.bits_int(N) % P


def generate():
    g = Grain()
    rc = [[g.field_rejection() for _ in range(T)] for _ in range(RF + RP)]
    while True:
        vals = [g.field_wide() for _ in range(2 * T)]
        if len(set(vals)) == 2 * T:
            break
    xs, ys = vals[:T], vals[T:]
    mds = [[pow((xs[i] + ys[j]) % P, P - 2, P) for j in range(T)] for i in range(T)]
    return rc, mds


def mont(v):
    """Montgomery form (R = 2^256) as 8 little-endian 32-bit limbs."""
    m = (v << 256) % P
    return ", ".join("0x%08x" % ((m >> (32 * i)) & 0xFFFFFFFF) for i in range(8))


def main():
    rc, mds = generate()
    print("/* Generated by tools/gen_poseidon.py. Do not edit. */")
    print("/* Poseidon P128Pow5T3 over the Pallas base field (Orchard PRF^nf). */")
    print("#pragma once")
    print("#include <stdint.h>")
    print("/* Montgomery form (R = 2^256), 8 little-endian 32-bit limbs, as zc_fe. */")
    print("static const uint32_t ZC_POSEIDON_RC_M[%d][3][8] = {" % len(rc))
    for r in rc:
        print("  {" + ", ".join("{" + mont(v) + "}" for v in r) + "},")
    print("};")
    print("static const uint32_t ZC_POSEIDON_MDS_M[3][3][8] = {")
    for r in mds:
        print("  {" + ", ".join("{" + mont(v) + "}" for v in r) + "},")
    print("};")


if __name__ == "__main__":
    main()
